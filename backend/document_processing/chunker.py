from typing import List


def chunking(
    chunks: List[str],
    chunk_size: int = 200,
) -> List[str]:
    """
    Remove repeated words at the boundaries of consecutive text chunks.

    The function compares the end of the previous chunk with the beginning
    of the current chunk. If the same words appear in both places, they are
    removed from the current chunk to avoid unnecessary repetition.

    Args:
        chunks: The list of text chunks generated by the chunker.
        max_words_to_check: Maximum number of boundary words to compare.

    Returns:
        A new list of chunks with duplicated boundary text removed.
    """
    # Validate the limit so the comparison loop always has a useful range.
    if chunk_size <= 0:
        raise ValueError("max_words_to_check must be greater than zero.")

    cleaned_chunks = []

    for chunk in chunks:
        current_words = chunk.split()

        # Skip empty chunks because they contain no useful text.
        if not current_words:
            continue

        # Compare against the last retained chunk, which may already be cleaned.
        if cleaned_chunks:
            previous_words = cleaned_chunks[-1].split()

            # Limit the comparison to words that could reasonably be overlap.
            max_overlap = min(
                len(previous_words),
                len(current_words),
                chunk_size,
            )

            duplicate_count = 0

            # Check the longest possible overlap first, then try shorter matches.
            for count in range(max_overlap, 0, -1):
                previous_end = previous_words[-count:]
                current_start = current_words[:count]

                if previous_end == current_start:
                    duplicate_count = count
                    break

            # Remove the matching words only when a duplicate boundary is found.
            if duplicate_count > 0:
                current_words = current_words[duplicate_count:]

        # Keep the chunk only if some meaningful text remains after cleanup.
        if current_words:
            cleaned_chunks.append(" ".join(current_words))

    return cleaned_chunks
